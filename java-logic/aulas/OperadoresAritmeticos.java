public class OperadoresAritmeticos {
    public static void main(String[] args) {
        // Soma
        System.out.println("Soma: \t\t\t" + (5 + 3));

        // Subtração
        System.out.println("Subtração: \t\t" + (5 - 3));

        // Multiplicação
        System.out.println("Multiplicação: \t\t" + (5 * 3));

        // Divisão
        System.out.println("Divisão: \t\t" + (5 / 3));

        // Resto da divisão
        System.out.println("Resto da divisão: \t" + (5 % 3));
    }
}
