public class OperadoresRelacionais {
    public static void main(String[] args) {
        // Igualdade
        System.out.println("Igualdade: \t\t" + (5 == 3));

        // Diferença
        System.out.println("Diferença: \t\t" + (5 != 3));

        // Maior que
        System.out.println("Maior que: \t\t" + (5 > 3));

        // Menor que
        System.out.println("Menor que: \t\t" + (5 < 3));

        // Maior ou igual a
        System.out.println("Maior ou igual a: \t" + (5 >= 3));

        // Menor ou igual a
        System.out.println("Menor ou igual a: \t" + (5 <= 3));
    }    
}
